import random
chars: list[str] = ["E", "C", "I", "C"]
ball_colors: list[str] = ["white", "red", "green", "brown", "red", "pink", "purple", "chocolate", "hotpink", "deeppink", "orange", "crimson", "magenta", "lavender", "seagreen", "beige"]
for c in chars:
	tl.fillcolor(random.choice(ball_colors))
	tl.begin_fill()
	tl.circle(80)
	tl.end_fill()
	tl.write(c, font=("Helvetica", 14))
	tl.up()
	tl.forward(100)
	tl.down()

